#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Simplified-Chinese catalogue tool for Materializr.

Two directions, both keeping the ENGLISH STRING as the key (see src/i18n.h):

  export  i18n_zh_catalogue.h  ->  zh-CN.json + zh-CN.csv
          Pull the translations out of the built header so they can be
          proof-read in a spreadsheet and re-imported later.

  build   zh-CN.json           ->  i18n_zh_catalogue.h
          Regenerate the header after editing the JSON/CSV. The English key
          is taken from tools/i18n_catalogue.py (the source of truth), so a
          translation can never drift onto the wrong key.

Usage:
  python3 gen_zh_catalogue.py export \\
      --header ../source/i18n_zh_catalogue.h \\
      --json ../translations/zh-CN.json --csv ../translations/zh-CN.csv

  python3 gen_zh_catalogue.py build \\
      --repo /path/to/materializr --json ../translations/zh-CN.json \\
      --out i18n_zh_catalogue.h

Notes:
  * C++ escaping round-trips exactly: \\\\, \\", \\n, \\t, \\r and \\xNN.
    A key that contains a newline MUST keep it, or the runtime lookup misses
    and the UI quietly falls back to English.
  * Missing keys in the JSON are written as "" (legal: tr() falls back).
"""
import argparse
import csv
import json
import os
import re
import sys

ENTRY = re.compile(r'\{ "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)" \}')
ESC_MAP = {'n': '\n', 't': '\t', 'r': '\r', '"': '"', '\\': '\\', '0': '\0'}


def unescape(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            if n in ESC_MAP:
                out.append(ESC_MAP[n])
                i += 2
                continue
            if n == 'x':
                out.append(chr(int(s[i + 2:i + 4], 16)))
                i += 4
                continue
            out.append(n)
            i += 2
            continue
        out.append(c)
        i += 1
    return ''.join(out)


def escape(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"')
    return s.replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r')


def cmd_export(args):
    text = open(args.header, encoding='utf-8').read()
    pairs = [(unescape(k), unescape(v)) for k, v in ENTRY.findall(text)]
    data = {k: v for k, v in pairs}
    os.makedirs(os.path.dirname(os.path.abspath(args.json)) or '.', exist_ok=True)
    with open(args.json, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    os.makedirs(os.path.dirname(os.path.abspath(args.csv)) or '.', exist_ok=True)
    with open(args.csv, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(['#', 'English (key)', '简体中文'])
        for i, (k, v) in enumerate(pairs, 1):
            w.writerow([i, k, v])
    print('exported %d entries -> %s, %s' % (len(pairs), args.json, args.csv))


def load_catalogue_keys(repo):
    tools = os.path.join(repo, 'tools')
    sys.path.insert(0, tools)
    from i18n_catalogue import CAT  # noqa: E402
    return [en for en, _ in CAT]


def cmd_build(args):
    keys = load_catalogue_keys(args.repo)
    if args.csv:
        # 用 Excel/WPS 校对过的 CSV 直接生成：列序为 #, English, 简体中文
        data = {}
        with open(args.csv, encoding='utf-8-sig', newline='') as f:
            for row in csv.reader(f):
                if len(row) >= 3 and row[0].strip().isdigit():
                    data[row[1]] = row[2]
    else:
        data = json.load(open(args.json, encoding='utf-8'))
    # The English catalogue and its generated header can drift (the header
    # ships strings the generator's CAT no longer lists). Our table keys off
    # the strings the UI actually hands to tr(), so KEEP the extras instead of
    # dropping them -- otherwise a rebuild silently loses translations for
    # every key the CAT hasn't caught up with.
    extras = sorted(set(data) - set(keys))
    if extras:
        print('note: %d keys translated here but absent from the English catalogue '
              '(kept anyway)' % len(extras))
    keys = list(keys) + extras
    lines = [
        '// GENERATED by tools/gen_zh_catalogue.py -- do not edit by hand.',
        '//',
        '// Simplified Chinese column. Same contract as the other catalogues: the',
        '// English string is the key, and a null translation falls back to English.',
        '#pragma once',
        '#include "i18n_catalogue.h"',
        '',
        'namespace materializr {',
        '',
        'inline const TrEntry kZhCatalogue[] = {',
    ]
    missing = 0
    for en in keys:
        tr = data.get(en, '')
        if not tr:
            missing += 1
        lines.append('    { "%s", "%s" },' % (escape(en), escape(tr)))
    lines += [
        '};',
        'inline constexpr int kZhCount =',
        '    static_cast<int>(sizeof(kZhCatalogue) / sizeof(kZhCatalogue[0]));',
        '',
        '} // namespace materializr',
        '',
    ]
    open(args.out, 'w', encoding='utf-8').write('\n'.join(lines))
    print('wrote %s: %d entries, %d untranslated' % (args.out, len(keys), missing))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest='cmd', required=True)
    e = sub.add_parser('export')
    e.add_argument('--header', required=True)
    e.add_argument('--json', required=True)
    e.add_argument('--csv', required=True)
    b = sub.add_parser('build')
    b.add_argument('--repo', required=True, help='Materializr checkout with tools/i18n_catalogue.py')
    b.add_argument('--json', help='en -> zh mapping (zh-CN.json)')
    b.add_argument('--csv', help='校对过的 zh-CN.csv（优先于 --json）')
    b.add_argument('--out', required=True)
    a = ap.parse_args()
    if a.cmd == 'build' and not (a.json or a.csv):
        ap.error('build 需要 --json 或 --csv')
    cmd_export(a) if a.cmd == 'export' else cmd_build(a)


if __name__ == '__main__':
    main()
